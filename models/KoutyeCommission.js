const mongoose = require('mongoose');

const koutyeCommissionSchema = new mongoose.Schema({
  koutye: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'Koutye',
    required: true
  },
  referral: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'KoutyeReferral',
    required: true
  },
  platform: {
    type: String,
    enum: ['48hoursready', 'msouwout', 'myplopplop', 'utility', 'sol', 'prolakay', 'tikelakay'],
    required: true
  },
  transactionId: {
    type: String
  },
  /* Copied from the referral it was earned on. Lets an organisation's
     dashboard total "commission generated by our team" without re-deriving
     who belonged where at the time. */
  organization: { type: String, default: '', index: true },
  serviceType: {
    type: String,
    /* 'ticket' added 15 Oct 2026: routes/referrals.js /ticket-sale has sent it
       since 3 Oct, and without it here EVERY paid Tike Lakay ticket's
       commission failed validation and was silently not written. Found by
       testing the door itself rather than the function behind it. */
    enum: ['package', 'ride', 'delivery', 'marketplace', 'utility', 'sol', 'talent', 'ticket'],
    default: 'package'
  },
  sourceAmount: {
    type: Number,
    required: true
  },
  platformFee: {
    type: Number
  },
  commissionRate: {
    type: Number,
    required: true
  },
  amount: {
    type: Number,
    required: true
  },
  currency: {
    type: String,
    default: 'HTG'
  },
  status: {
    type: String,
    enum: ['pending', 'validated', 'approved', 'paid', 'rejected', 'expired'],
    default: 'pending'
  },
  description: String,
  sourceTransaction: {
    type: String
  },
  earnedAt: {
    type: Date,
    default: Date.now
  },
  validatedAt: Date,
  approvedAt: Date,
  paidAt: Date,
  expiresAt: Date,
  rejectionReason: String
}, {
  timestamps: true
});

koutyeCommissionSchema.index({ koutye: 1, createdAt: -1 });
koutyeCommissionSchema.index({ status: 1 });
koutyeCommissionSchema.index({ platform: 1 });
koutyeCommissionSchema.index({ referral: 1 });

module.exports = mongoose.model('KoutyeCommission', koutyeCommissionSchema);
